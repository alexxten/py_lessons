# ТИПЫ ДАННЫХ: mutable (изменяемые) / immutable (неизменяемые)

# Неизменяемые (immutable) типы
# int, float - числа
# str - строки
# bool - булевы значения
# None - "пустышка"
# tuple - кортежи

# Изменяемые (mutable) типы
# list - списки
# set - множества
# dict - словари


print("=== ДЕМОНСТРАЦИЯ id() ===")
print("--- Неизменяемый тип (int) ---")
# a - это int, он неизменяемый. При изменении значения создается новый объект
a: int = 1
print(f"a = {a}, id: {id(a)}")
a = a + 1
print(f"a = {a}, id: {id(a)} (id изменился - создан новый объект)")

print("\n")

print("--- Изменяемый тип (list) ---")
b = [1, 2, 3]
print(f"b = {b}, id: {id(b)}")
b.append(4)
print(f"b = {b}, id: {id(b)} (id НЕ изменился - объект тот же)")

print("\n")

# СТРОКИ
print("=== СТРОКИ ===")
a_str = "a"  # можно использовать как ", так и ' кавычки
print(f"Eto stroka, var a = {a}, a stroka a_str = {a_str}")

print("\n")

# "СТРУКТУРЫ" - СПИСКИ
print("=== СПИСКИ (list) ===")
a_list = [1, 2, 3, "2", True, 1]  # список может содержать разные типы данных
print(f"Исходный список a_list: {a_list}")

a_list.append(4)  # добавляем элемент в конец списка
print(f"После a_list.append(4): {a_list}")

b_list = [1, 5, 6]

# Конкатенация (склеивание) списков
print(f"a_list + b_list = {a_list + b_list} (создается новый список)")

a_list.extend(b_list)  # расширяем первый список элементами второго
print(f"После a_list.extend(b_list): {a_list} (исходный список изменился)")

print("\n--- Перебор списка циклом for ---")
for i in a_list:
    print(f"  Элемент: {i}")

print("\n")

# СЛОВАРИ
print("=== СЛОВАРИ (dict) ===")
a_dict = {1: "a", 2: "b", 3: "c"}  # ключ: значение
print(f"Словарь a_dict: {a_dict}")

b_dict = {1: "a", 1: "b", 3: "c"}  # ключи должны быть уникальны
print(f"Словарь b_dict (с дублем ключа 1): {b_dict}")
print(f"b_dict[1] = '{b_dict[1]}' (последнее значение для ключа 1 перезаписалось)")

# Важно: ключами в словаре могут быть ТОЛЬКО immutable типы

print("\n")

# МНОЖЕСТВА
print("=== МНОЖЕСТВА (set) ===")
a_set = {1, 3, 4, 1}  # дубликаты автоматически удаляются
print(f"{a_set} (дубликат 1 удален)")
b_set = {3}
print(f"Пересечение a_set & b_set: {a_set & b_set} (общие элементы)")


# КОРТЕЖИ
print("=== КОРТЕЖИ (tuple) ===")
a_tuple = (1, 2, 3, 1)  # неизменяемый аналог списка
print(f"Кортеж a_tuple = {a_tuple}")